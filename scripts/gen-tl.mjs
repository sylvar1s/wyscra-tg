// Generates MTProto TL schema + TypeScript types from spec/mtproto.tl and spec/api.tl.
// Usage: node scripts/gen-tl.mjs [--fetch]   (--fetch downloads the latest schema from tdesktop)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const SRC = 'https://raw.githubusercontent.com/telegramdesktop/tdesktop/dev/Telegram/SourceFiles/mtproto/';
const spec = (f) => new URL(`../spec/${f}`, import.meta.url);
const OUT = new URL('../src/mtproto/generated/', import.meta.url);

if (process.argv.includes('--fetch')) {
  for (const f of ['scheme/api.tl', 'scheme/mtproto.tl', 'mtproto_dc_options.cpp']) {
    const r = await fetch(SRC + f);
    if (!r.ok) throw new Error(`${f}: HTTP ${r.status}`);
    writeFileSync(spec(f.split('/').pop()), await r.text());
  }
}

const apiTl = readFileSync(spec('api.tl'), 'utf8');
const mtTl = readFileSync(spec('mtproto.tl'), 'utf8');
const layer = Number(/\/\/\s*LAYER\s+(\d+)/.exec(apiTl)?.[1]);
if (!layer) throw new Error('LAYER not found in api.tl');

/** @returns {{id:number,name:string,method:boolean,type:string,params:{name:string,type:string}[],generic:boolean}[]} */
function parse(text) {
  const out = [];
  let method = false;
  for (let line of text.split('\n')) {
    line = line.replace(/\/\/.*$/, '').trim();
    if (!line) continue;
    if (line === '---functions---') { method = true; continue; }
    if (line === '---types---') { method = false; continue; }
    const m = /^([\w.]+)#([0-9a-f]+)\s*(.*?)\s*=\s*([^;]+);$/.exec(line);
    if (!m) continue; // core/built-in definitions without ids
    const [, name, hex, rest, type] = m;
    if (name === 'vector' || /\s/.test(type.trim())) continue; // built-in vector, handled by the codec
    let generic = false;
    const params = [];
    for (const tok of rest.split(/\s+/).filter(Boolean)) {
      if (tok.startsWith('{')) { generic = true; continue; }
      const i = tok.indexOf(':');
      params.push({ name: tok.slice(0, i), type: tok.slice(i + 1) });
    }
    out.push({ id: parseInt(hex, 16) >>> 0, name, method, type: type.trim(), params, generic });
  }
  return out;
}

// In mtproto.tl, `string` fields carry binary data (pq, dh_prime, encrypted_answer...). Treat them as bytes.
const mtEntries = parse(mtTl);
for (const e of mtEntries) {
  if (e.name === 'rpc_error') continue;
  for (const p of e.params) if (p.type === 'string') p.type = 'bytes';
}
const entries = [...mtEntries, ...parse(apiTl)];
const byName = new Map();
for (const e of entries) byName.set(`${e.method ? 'm' : 'c'}:${e.name}`, e); // api.tl overrides duplicates
const all = [...byName.values()];
const ctors = all.filter((e) => !e.method);
const methods = all.filter((e) => e.method);

// ---------- runtime schema ----------
const compact = all.map((e) => [e.id, e.name, e.method ? 1 : 0, e.type, e.params.map((p) => `${p.name}:${p.type}`).join(' ')]);
mkdirSync(OUT, { recursive: true });
writeFileSync(
  new URL('schema.ts', OUT),
  `// AUTO-GENERATED by scripts/gen-tl.mjs. Do not edit by hand.\n` +
    `/** API layer of the bundled schema. */\nexport const LAYER = ${layer};\n` +
    `/** [id, name, isMethod, type, "param:type ..."] */\n` +
    `export const SCHEMA: Array<[number, string, 0 | 1, string, string]> = ${JSON.stringify(compact)};\n`,
);

// ---------- RSA keys and DCs from tdesktop ----------
const cpp = readFileSync(spec('mtproto_dc_options.cpp'), 'utf8');
const pems = (name) => {
  const block = new RegExp(`${name}\\[\\] = \\{([\\s\\S]*?)\\};`).exec(cpp)[1];
  return [...block.matchAll(/-----BEGIN RSA PUBLIC KEY-----[\s\S]*?-----END RSA PUBLIC KEY-----/g)].map((m) =>
    m[0].replace(/\\n\\\r?\n/g, '\n').replace(/\\\r?\n/g, ''),
  );
};
const dcs = (name) => {
  const block = new RegExp(`${name}\\[\\] = \\{([\\s\\S]*?)\\};`).exec(cpp)[1];
  return [...block.matchAll(/\{\s*(\d+),\s*"([^"]+)"\s*,\s*(\d+)\s*\}/g)].map((m) => ({ id: +m[1], ip: m[2], port: +m[3] }));
};
writeFileSync(
  new URL('dc.ts', OUT),
  `// AUTO-GENERATED by scripts/gen-tl.mjs from tdesktop sources.\n` +
    `export const PUBLIC_KEYS: string[] = ${JSON.stringify(pems('kPublicRSAKeys'), null, 2)};\n` +
    `export const TEST_PUBLIC_KEYS: string[] = ${JSON.stringify(pems('kTestPublicRSAKeys'), null, 2)};\n` +
    `export const DCS = ${JSON.stringify(dcs('kBuiltInDcs'))};\n` +
    `export const DCS_IPV6 = ${JSON.stringify(dcs('kBuiltInDcsIPv6'))};\n` +
    `export const TEST_DCS = ${JSON.stringify(dcs('kBuiltInDcsTest'))};\n` +
    `export const TEST_DCS_IPV6 = ${JSON.stringify(dcs('kBuiltInDcsIPv6Test'))};\n`,
);

// ---------- TypeScript types ----------
const pascal = (s) => s[0].toUpperCase() + s.slice(1);
const split = (full) => {
  const i = full.lastIndexOf('.');
  return i < 0 ? ['', full] : [full.slice(0, i), full.slice(i + 1)];
};
const qualify = (ns, name) => `tl.${ns ? ns + '.' : ''}${name}`;
const ctorRef = (full) => { const [ns, n] = split(full); return qualify(ns, pascal(n)); };
const typeRef = (full) => { const [ns, n] = split(full); return qualify(ns, `Type${pascal(n)}`); };
const ctorNames = new Set(ctors.map((c) => c.name));
const typeNames = new Set(ctors.map((c) => c.type));

function tsType(t) {
  const cond = /^[\w]+\.\d+\?(.+)$/.exec(t);
  if (cond) t = cond[1];
  if (t.startsWith('!')) return 'tl.AnyRequest';
  const vec = /^[Vv]ector<(.+)>$/.exec(t);
  if (vec) return `${tsType(vec[1])}[]`;
  switch (t) {
    case 'int': case 'double': return 'number';
    case 'long': return 'bigint';
    case 'int128': case 'int256': case 'bytes': return 'Uint8Array';
    case 'string': return 'string';
    case 'Bool': case 'true': return 'boolean';
    case 'X': case 'Object': return 'any';
    case '#': return 'number';
  }
  if (t.startsWith('%')) return ctorRef(t.slice(1));
  if (typeNames.has(t)) return typeRef(t);
  if (ctorNames.has(t)) return ctorRef(t); // bare constructor reference
  return 'any';
}

function iface(e, nameOverride) {
  const [, n] = split(e.name);
  const lines = [`export interface ${nameOverride ?? pascal(n)} {`, `  _: '${e.name}';`];
  for (const p of e.params) {
    if (p.type === '#') continue;
    const optional = /^\w+\.\d+\?/.test(p.type);
    lines.push(`  ${p.name}${optional ? '?' : ''}: ${tsType(p.type)};`);
  }
  lines.push('}');
  return lines.join('\n');
}

// group by namespace
const ns = new Map();
const add = (space, code) => { if (!ns.has(space)) ns.set(space, []); ns.get(space).push(code); };
for (const c of ctors) add(split(c.name)[0], iface(c));
const unions = new Map();
for (const c of ctors) { if (!unions.has(c.type)) unions.set(c.type, []); unions.get(c.type).push(c.name); }
for (const [type, names] of unions) {
  const [space, n] = split(type);
  if (type === 'Bool' || type === 'True') continue;
  add(space, `export type Type${pascal(n)} = ${names.map(ctorRef).join(' | ')};`);
}
for (const m of methods) add(split(m.name)[0], iface(m, `${pascal(split(m.name)[1])}Request`));

const ts = [];
ts.push('// AUTO-GENERATED by scripts/gen-tl.mjs. Do not edit by hand.');
ts.push(`// Telegram API layer ${layer}`);
ts.push('/* eslint-disable */');
ts.push('export namespace tl {');
ts.push('  /** Any TL object. */');
ts.push('  export type Object = { _: string; [key: string]: any };');
ts.push('  /** Any method request object. */');
ts.push('  export type AnyRequest = { _: keyof Methods; [key: string]: any };');
for (const [space, items] of [...ns].sort(([a], [b]) => a.localeCompare(b))) {
  const ind = space ? '    ' : '  ';
  if (space) ts.push(`  export namespace ${space} {`);
  for (const it of items) ts.push(it.split('\n').map((l) => ind + l).join('\n'));
  if (space) ts.push('  }');
}
ts.push('}\n');

const resultType = (m) => (m.generic && m.type === 'X' ? 'any' : m.type === 'Bool' ? 'boolean' : tsType(m.type));
const reqRef = (m) => { const [s, n] = split(m.name); return qualify(s, `${pascal(n)}Request`); };
const hasRequired = (m) => m.params.some((p) => p.type !== '#' && !/^\w+\.\d+\?/.test(p.type));

ts.push('/** Every API method: params and result type. */');
ts.push('export interface Methods {');
for (const m of methods) ts.push(`  '${m.name}': { params: Omit<${reqRef(m)}, '_'>; result: ${resultType(m)} };`);
ts.push('}\n');

ts.push('type Fn<M extends keyof Methods, Req extends boolean> = Req extends true');
ts.push("  ? (params: Methods[M]['params']) => Promise<Methods[M]['result']>");
ts.push("  : (params?: Methods[M]['params']) => Promise<Methods[M]['result']>;\n");
ts.push('/** `client.api.messages.sendMessage({...})` — typed access to every method. */');
ts.push('export interface ApiProxy {');
const groups = new Map();
for (const m of methods) {
  const [s, n] = split(m.name);
  if (!groups.has(s)) groups.set(s, []);
  groups.get(s).push(`${n}: Fn<'${m.name}', ${hasRequired(m)}>;`);
}
for (const [s, items] of groups) {
  if (!s) for (const it of items) ts.push(`  ${it}`);
  else ts.push(`  ${s}: {\n${items.map((i) => `    ${i}`).join('\n')}\n  };`);
}
ts.push('}');
writeFileSync(new URL('tl.ts', OUT), ts.join('\n') + '\n');

console.log(`Generated layer ${layer}: ${ctors.length} constructors, ${methods.length} methods, ${pems('kPublicRSAKeys').length} RSA keys`);
