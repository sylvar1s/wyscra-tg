// Generates fully-typed Bot API bindings from spec/bot-api.json.
// Usage: node scripts/gen-bot-api.mjs [--fetch]
// --fetch downloads the latest spec first.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const SPEC_URL = 'https://raw.githubusercontent.com/PaulSonOfLars/telegram-bot-api-spec/main/api.json';
const SPEC_PATH = new URL('../spec/bot-api.json', import.meta.url);
const OUT_DIR = new URL('../src/bot/generated/', import.meta.url);

if (process.argv.includes('--fetch')) {
  const res = await fetch(SPEC_URL);
  if (!res.ok) throw new Error(`Failed to fetch spec: ${res.status}`);
  writeFileSync(SPEC_PATH, await res.text());
}

const spec = JSON.parse(readFileSync(SPEC_PATH, 'utf8'));
mkdirSync(OUT_DIR, { recursive: true });

const cap = (s) => s[0].toUpperCase() + s.slice(1);
const doc = (lines, href, indent = '') => {
  const body = (Array.isArray(lines) ? lines : [lines])
    .filter(Boolean)
    .map((l) => l.replaceAll('*/', '*\\/'));
  if (href) body.push(`@see ${href}`);
  if (!body.length) return '';
  return `${indent}/**\n${body.map((l) => `${indent} * ${l}`).join('\n')}\n${indent} */\n`;
};

function mapOne(t) {
  if (t.startsWith('Array of ')) {
    const inner = mapOne(t.slice(9));
    return inner.includes('|') ? `Array<${inner}>` : `${inner}[]`;
  }
  switch (t) {
    case 'Integer':
    case 'Float':
      return 'number';
    case 'String':
      return 'string';
    case 'Boolean':
      return 'boolean';
    case 'True':
      return 'true';
    default:
      return t;
  }
}

// Detects discriminator literals like: Type of the result, must be *photo* / always “creator”
const LITERAL_RE = /(?:must be|always)\s+[“"*]?([a-z_]+)[”"*]?/;

// Fields that have a matching parse_mode sibling accept html``/md`` Formatted text.
function formattable(fields) {
  const names = new Set(fields.map((f) => f.name));
  const out = new Set();
  if (names.has('parse_mode')) for (const n of ['text', 'caption']) if (names.has(n)) out.add(n);
  for (const n of names) if (n.endsWith('_parse_mode') && names.has(n.slice(0, -11))) out.add(n.slice(0, -11));
  return out;
}

function fieldType(field, fmtFields) {
  if (fmtFields?.has(field.name)) return 'string | Formatted';
  if (
    ['type', 'status', 'source'].includes(field.name) &&
    field.types.length === 1 &&
    field.types[0] === 'String'
  ) {
    const m = LITERAL_RE.exec(field.description);
    if (m) return JSON.stringify(m[1]);
  }
  const types = field.types.map(mapOne);
  // Fields that accept "attach://<name>" can take an InputFile directly; the client uploads it.
  if (field.types.includes('String') && /attach:\/\//.test(field.description) && !types.includes('InputFile')) {
    types.push('InputFile');
  }
  return [...new Set(types)].join(' | ');
}

const out = [];
out.push('// AUTO-GENERATED by scripts/gen-bot-api.mjs. Do not edit by hand.');
out.push(`// ${spec.version} (${spec.release_date})`);
out.push("import type { InputFile } from '../input-file.js';");
out.push("import type { Formatted } from '../format.js';\n");
out.push(`export const BOT_API_VERSION = ${JSON.stringify(spec.version)};\n`);

// ---- Types ----
for (const t of Object.values(spec.types)) {
  if (t.name === 'InputFile') continue;
  out.push(doc(t.description, t.href).trimEnd());
  if (t.subtypes?.length) {
    out.push(`export type ${t.name} = ${t.subtypes.map(mapOne).join(' | ')};\n`);
  } else if (t.fields?.length) {
    out.push(`export interface ${t.name} {`);
    const ff = formattable(t.fields);
    for (const f of t.fields) {
      out.push(doc(f.description, null, '  ').trimEnd());
      out.push(`  ${f.name}${f.required ? '' : '?'}: ${fieldType(f, ff)};`);
    }
    out.push('}\n');
  } else {
    out.push(`export interface ${t.name} {}\n`);
  }
}

// ---- Method params ----
const methods = Object.values(spec.methods);
for (const m of methods) {
  if (!m.fields?.length) continue;
  out.push(doc([`Parameters for {@link ApiMethods.${m.name}}`], m.href).trimEnd());
  out.push(`export interface ${cap(m.name)}Params {`);
  const ff = formattable(m.fields);
  for (const f of m.fields) {
    out.push(doc(f.description, null, '  ').trimEnd());
    out.push(`  ${f.name}${f.required ? '' : '?'}: ${fieldType(f, ff)};`);
  }
  out.push('}\n');
}

// ---- Method map ----
out.push('/** Map of every Bot API method to its parameters and result type. */');
out.push('export interface ApiMethods {');
for (const m of methods) {
  const params = m.fields?.length ? `${cap(m.name)}Params` : 'Record<string, never>';
  const result = [...new Set(m.returns.map(mapOne))].join(' | ');
  out.push(doc(m.description, m.href, '  ').trimEnd());
  out.push(`  ${m.name}(params: ${params}): ${result};`);
}
out.push('}\n');

const updateTypes = spec.types.Update.fields.map((f) => f.name).filter((n) => n !== 'update_id');
out.push('/** Every update kind the Bot API can deliver. */');
out.push(`export const UPDATE_TYPES = ${JSON.stringify(updateTypes)} as const;`);
out.push('export type UpdateType = (typeof UPDATE_TYPES)[number];\n');

const withParseMode = methods.filter((m) => m.fields?.some((f) => f.name === 'parse_mode')).map((m) => m.name);
out.push('/** Methods that take a top-level parse_mode (used for the default parseMode option). */');
out.push(`export const PARSE_MODE_METHODS: ReadonlySet<string> = new Set(${JSON.stringify(withParseMode)});\n`);

writeFileSync(new URL('types.ts', OUT_DIR), out.join('\n'));

// ---- Method wrappers ----
const api = [];
api.push('// AUTO-GENERATED by scripts/gen-bot-api.mjs. Do not edit by hand.');
api.push("import type * as T from './types.js';\n");
api.push('/** Optional per-call settings. */');
api.push('export interface CallOptions {\n  /** Abort the request. */\n  signal?: AbortSignal;\n}\n');
api.push('/** Typed wrappers for every Bot API method. */');
api.push('export abstract class ApiMethodsBase {');
api.push('  /** Calls any Bot API method by name. */');
api.push(
  '  abstract call<M extends keyof T.ApiMethods>(method: M, params?: Parameters<T.ApiMethods[M]>[0], options?: CallOptions): Promise<ReturnType<T.ApiMethods[M]>>;\n',
);
for (const m of methods) {
  const has = m.fields?.length;
  const required = has && m.fields.some((f) => f.required);
  const p = has ? `params${required ? '' : '?'}: T.${cap(m.name)}Params` : 'params?: Record<string, never>';
  const result = [...new Set(m.returns.map(mapOne))]
    .map((r) => r.replace(/^([A-Z]\w*)/, 'T.$1').replace(/<([A-Z]\w*)/g, '<T.$1').replace(/\| ([A-Z]\w*)/g, '| T.$1'))
    .join(' | ');
  api.push(doc(m.description, m.href, '  ').trimEnd());
  api.push(`  ${m.name}(${p}, options?: CallOptions): Promise<${result}> {`);
  api.push(`    return this.call('${m.name}', params as never, options);`);
  api.push('  }\n');
}
api.push('}');
writeFileSync(new URL('methods.ts', OUT_DIR), api.join('\n') + '\n');

console.log(`Generated ${Object.keys(spec.types).length} types and ${methods.length} methods for ${spec.version}`);
